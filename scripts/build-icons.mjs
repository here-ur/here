import fs from 'node:fs/promises';
import sharp from 'sharp';

// KRDS optical keylines inside a 24px grid. Shapes keep their original proportions.
// Measure painted bounds, including strokes, so the live area retains its padding.
const shapes = {
  square: [18, 18], circle: [20, 20], horizontal: [20, 16], vertical: [16, 20],
};
const groups = {
  circle: 'info check checkFilled clock refresh sun add close',
  horizontal: 'back down forward keyboard soundOn soundOff hangUp captions email menu wind chev chev2 arrow heart swap',
  vertical: 'mic micOff send lock pin paintbrush pencil drop flame profile library',
};
const source = await fs.readFile(new URL('./icons/iconsax-free.source.svg', import.meta.url), 'utf8');
const symbols = [...source.matchAll(/<symbol\b([^>]*)>([\s\S]*?)<\/symbol>/g)];
const output = [], report = [];
const density = 40;

async function bounds(content) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="1280" viewBox="-4 -4 32 32" fill="none" color="black">${content}</svg>`;
  const { data, info } = await sharp(Buffer.from(svg)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let x0 = info.width, y0 = info.height, x1 = -1, y1 = -1;
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
    if (data[(y * info.width + x) * 4 + 3] < 16) continue;
    x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y);
  }
  if (x1 < 0) throw new Error('Empty icon');
  return { width: (x1 - x0 + 1) / density, height: (y1 - y0 + 1) / density,
    cx: (x0 + x1 + 1) / (2 * density) - 4, cy: (y0 + y1 + 1) / (2 * density) - 4 };
}

for (const [, attrs, content] of symbols) {
  const id = attrs.match(/id="([^"]+)"/)[1];
  const keyline = Object.entries(groups).find(([, names]) => names.split(' ').includes(id))?.[0] ?? 'square';
  const [width, height] = shapes[keyline];
  let scale = 1, tx = 0, ty = 0;
  const render = () => `<g transform="translate(${tx} ${ty}) scale(${scale})">${content.replace(/stroke-width="[^"]+"/g, `stroke-width="${1.5 / scale}"`)}</g>`;
  // Compensate stroke width after scaling; final stroke is exactly 1.5 units at 24px.
  for (let i = 0; i < 5; i++) {
    const b = await bounds(render());
    const fit = Math.min(width / b.width, height / b.height);
    scale *= fit; tx = 12 + (tx - b.cx) * fit; ty = 12 + (ty - b.cy) * fit;
  }
  const b = await bounds(render());
  if (b.width > width + .06 || b.height > height + .06 || Math.abs(b.cx - 12) > .04 || Math.abs(b.cy - 12) > .04) {
    throw new Error(`Keyline overflow or misalignment: ${id}`);
  }
  output.push(`<symbol ${attrs.trim()} data-keyline="${keyline}">${render()}</symbol>`);
  report.push({ id, keyline, bounds: b, scale, stroke: content.includes('stroke-width=') ? 1.5 : null });
}
await fs.writeFile(new URL('../public/icons/iconsax-free.svg', import.meta.url),
  `<!-- Generated by scripts/build-icons.mjs; Iconsax Free, see NOTICE.md. -->\n<svg xmlns="http://www.w3.org/2000/svg">\n${output.join('\n')}\n</svg>\n`);
await fs.writeFile(new URL('./icons/keylines.json', import.meta.url), JSON.stringify(report, null, 2) + '\n');
console.log(`Verified ${report.length} icons: centered keylines and 1.5px strokes at 24px.`);
