// 병명·약·치료 같은 의료 표현. 약속·약간·예약·요약·계약·의사소통·기술 같은 일상어는 걸리지 않게 짰다.
// 리포트의 자주 한 말에서 이런 말은 보여 주지 않는다.
const CLINICAL = [
  /진단|처방|복용|투약|약물|알약|약국|수면\s*유도제|수면제|진통제|안정제|항우울제|영양제|보충제|진료|입원|응급실|한의원/,
  /치료|병원|정신과|정신\s*건강\s*의학과|검사\s*받/,
  /우울증|공황|불안\s*장애|강박|조울|양극성|ADHD|PTSD|트라우마|섭식\s*장애|불면증|질환|질병|증상|병명/i,
  /(^|[^가-힣])약(을|이|은|도|만|부터)?\s*(먹|드시|드세|챙기|챙겨|복용|끊|줄이|늘리|바꾸)/,
  /(^|[^가-힣])약사/,
  /의사\s*(선생님|한테|에게|와\s|랑|상담)/,
];

export function isClinical(text: string) {
  return CLINICAL.some((pattern) => pattern.test(text));
}
